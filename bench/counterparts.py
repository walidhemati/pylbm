"""Same-GPU head-to-head with established lattice-Boltzmann codes.

    python bench/counterparts.py --quick   # < 60 s of GPU time, < 1 GB GPU memory
    python bench/counterparts.py --full    # publishable; run on an otherwise idle GPU

Both write ``results/counterparts.json`` (``--quick`` marks it provisional).

Counterparts, each pinned to a commit and measured on the same GPU in the same session as
pylbm's own kernels:

* **FluidX3D** (M. Lehmann, OpenCL, https://github.com/ProjectPhysX/FluidX3D), D2Q9 and D3Q19,
  SRT (= BGK) collision, FP32 arithmetic with FP32, FP16S or FP16C storage. Its benchmark
  setup (periodic box at rest, ``#define BENCHMARK``) is used with one alteration: the
  ``main_setup()`` of the benchmark is replaced by a timing harness that reads the lattice size
  from the environment and prints the wall time of each timed region (``_fx_setup_cpp``). The
  alteration is applied to a copy of the pinned source tree, the altered files carry a notice,
  and this script is their published source (FluidX3D license, clauses 1 and 5).
* **Lettuce** (Bedrunka et al. 2021, PyTorch, https://github.com/lettucecfd/lettuce) in its
  own virtual environment, both its PyTorch path and its generated native CUDA kernel, with the
  case of its ``lettuce benchmark`` command (periodic Taylor--Green vortex, BGK, fp32).

All codes are scored with pylbm's metric: MLUPS (median, min, max of >= 5 timed regions of
>= ``min_time`` each, after warm-up), the minimal traffic model of 2 q s bytes per lattice
update, and the fraction of the measured copy bandwidth from ``results/rtx3070-laptop.json``.

Environment: ``PYLBM_REF_DIR`` (default ``../_ref``: the FluidX3D and Lettuce clones),
``CP_LETTUCE_PYTHON`` (default ``~/.venvs/cp-lettuce/bin/python``).
"""

