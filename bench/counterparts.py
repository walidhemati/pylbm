STORAGE_BYTES = {"fp32": 4, "fp16": 2, "bf16": 2, "fp16s": 2, "fp16c": 2}


@dataclass
class CPlan:
    """What the head-to-head measures."""

    name: str
    sizes_2d: list[int]
    sizes_3d: list[int]
    lettuce_3d: list[int]  # Lettuce's PyTorch path needs several copies of f
    min_time: float
    repeats: int


PLANS = {
    "quick": CPlan("quick", [1024], [64], [64], 0.1, 5),
    "full": CPlan("full", [1024, 4096], [128, 256], [128, 192, 256], 0.5, 5),
}
PYLBM_VARIANTS = [("triton", "fused"), ("cupy-cuda-c", "fused-aa"), ("triton", "fused-fp16"),
                  ("cupy-cuda-c", "fused-aa-fp16")]
FX_STORAGES = ["fp32", "fp16s", "fp16c"]


def log(msg: str) -> None:
    print(msg, flush=True)


def _git_head(path: Path) -> str | None:
    try:
        r = subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True,
                           text=True, timeout=10)
        return r.stdout.strip() or None
    except Exception:
        return None


def _record(code: str, variant: str, lattice: str, storage: str, problem: str,
            size: list[int], mlups: list[float], steps: int, copy_bw: float,
            notes: str = "", **extra: object) -> dict:
    q = 9 if lattice == "D2Q9" else 19
    bpu = 2 * q * STORAGE_BYTES[storage]
    med = float(np.median(mlups))
    eff = med * 1e6 * bpu / 1e9
    return {"code": code, "variant": variant, "lattice": lattice, "collision": "bgk",
            "arithmetic": "fp32", "storage": storage, "problem": problem, "size": size,
            "metric": "MLUPS", "repeats": len(mlups), "median": med, "min": float(min(mlups)),
            "max": float(max(mlups)), "steps_per_repeat": steps, "bytes_per_unit": bpu,
            "effective_GBs": eff, "pct_copy_bw": 100 * eff / copy_bw,
            "pct_spec_bw": 100 * eff / SPEC_BW, "notes": notes, **extra}


def _log_run(r: dict) -> None:
    log(f"  {r['code']:9s} {r['variant']:24s} {r['lattice']} {'x'.join(map(str, r['size'])):>13s}"
        f" {r['median']:9.1f} MLUPS {r['effective_GBs']:6.1f} GB/s {r['pct_copy_bw']:5.1f}% copy")


# ----------------------------------------------------------------------------- FluidX3D
_FX_NOTICE = (f"// ALTERED SOURCE: generated by pylbm bench/counterparts.py from FluidX3D commit "
              f"{FX_COMMIT}.\n// Not the original FluidX3D; see "
              f"https://github.com/ProjectPhysX/FluidX3D for the original software.\n")

_FX_HARNESS = r"""#ifdef BENCHMARK
#include "info.hpp"
#include <chrono>
#include <cstdio>
#include <cstdlib>
// pylbm harness (replaces the original benchmark main_setup): same LBM object and initial state
// as the original benchmark (periodic box, rho=1, u=0, nu=1), but sizes come from CP_SIZES
// ("nx,ny,nz;nx,ny,nz;...") and each timed region is reported as a CP_RESULT line.
static double cp_seconds(const std::chrono::steady_clock::time_point t0) {
	return std::chrono::duration<double>(std::chrono::steady_clock::now()-t0).count();
}
void main_setup() {
	const char* sizes = getenv("CP_SIZES");
	const char* rep = getenv("CP_REPEATS");
	const char* mt = getenv("CP_MIN_TIME");
	const ulong repeats = rep!=nullptr ? strtoull(rep, nullptr, 10) : 5ull;
	const double min_time = mt!=nullptr ? atof(mt) : 0.5;
	const char* p = sizes!=nullptr ? sizes : "256,256,256";
	while(*p) {
		uint nx=1u, ny=1u, nz=1u;
		if(sscanf(p, "%u,%u,%u", &nx, &ny, &nz)!=3) break;
		{
			LBM lbm(nx, ny, nz, 1.0f);
			ulong steps = 20ull;
			lbm.run(steps, steps); // initialisation and warm-up
			while(true) { // calibrate: one timed region >= min_time
				const auto t0 = std::chrono::steady_clock::now();
				lbm.run(steps, steps);
				const double dt = cp_seconds(t0);
				if(dt>=min_time) break;
				const double grow = fmin(10.0, fmax(2.0, 1.2*min_time/fmax(dt, 1E-6)));
				steps = (ulong)((double)steps*grow);
			}
			for(ulong r=0ull; r<repeats; r++) {
				const auto t0 = std::chrono::steady_clock::now();
				lbm.run(steps, steps);
				const double dt = cp_seconds(t0);
				printf("\nCP_RESULT nx=%u ny=%u nz=%u cells=%llu steps=%llu seconds=%.9f\n", nx, ny,
					nz, (unsigned long long)lbm.get_N(), (unsigned long long)steps, dt);
				fflush(stdout);
			}
		}
		while(*p && *p!=';') p++;
		if(*p==';') p++;
	}
}
#endif // BENCHMARK
"""


def _fx_defines(text: str, lattice: str, storage: str) -> str:
    on = {lattice, "SRT", "BENCHMARK"} | ({"FP16S"} if storage == "fp16s" else set()) | (
        {"FP16C"} if storage == "fp16c" else set())
    for name in ("D2Q9", "D3Q15", "D3Q19", "D3Q27", "SRT", "TRT", "FP16S", "FP16C", "BENCHMARK"):
        pat = re.compile(rf"^(//)?#define {name}\b", re.M)
        if not pat.search(text):
            raise RuntimeError(f"defines.hpp: no '#define {name}' line")
        text = pat.sub(("" if name in on else "//") + f"#define {name}", text, count=1)
    return _FX_NOTICE + text


def _fx_setup_cpp(text: str) -> str:
    i = text.index("#ifdef BENCHMARK")
    j = text.index("#endif // BENCHMARK", i) + len("#endif // BENCHMARK")
    if "void main_setup() { // benchmark" not in text[i:j]:
        raise RuntimeError("setup.cpp: benchmark main_setup not found")
    return _FX_NOTICE + text[:i] + _FX_HARNESS + text[j:]


def fx_build(lattice: str, storage: str) -> Path:
    """Build (or reuse) an altered FluidX3D binary for one velocity set and storage format."""
    head = _git_head(FX_SRC)
    if head != FX_COMMIT:
        raise RuntimeError(f"{FX_SRC} is at {head}, expected pinned commit {FX_COMMIT}")
    src = FX_SRC / "src"
    defines = _fx_defines((src / "defines.hpp").read_text(), lattice, storage)
    setup = _fx_setup_cpp((src / "setup.cpp").read_text())
    key = hashlib.sha256("\n".join([FX_COMMIT, defines, setup, *FX_CFLAGS, *FX_LDLIBS])
                         .encode()).hexdigest()[:16]
    d = FX_BUILD / f"{lattice}-{storage}"
    exe = d / "bin" / "FluidX3D"
    if exe.exists() and (d / "stamp").exists() and (d / "stamp").read_text() == key:
        return exe
    log(f"  building FluidX3D {lattice} {storage} in {d}")
    if d.exists():
        shutil.rmtree(d)
    shutil.copytree(src, d / "src")
    shutil.copy(FX_SRC / "LICENSE.md", d / "LICENSE.md")
    (d / "src" / "defines.hpp").write_text(defines)
    (d / "src" / "setup.cpp").write_text(setup)
    (d / "temp").mkdir()
    (d / "bin").mkdir()

    def compile_one(cpp: Path) -> None:
        subprocess.run(["g++", "-c", f"src/{cpp.name}", "-o", f"temp/{cpp.stem}.o", *FX_CFLAGS],
                       cwd=d, check=True, capture_output=True, text=True)

    with cf.ThreadPoolExecutor(BUILD_JOBS) as ex:
        list(ex.map(compile_one, sorted((d / "src").glob("*.cpp"))))
    objs = sorted(str(p.relative_to(d)) for p in (d / "temp").glob("*.o"))
    subprocess.run(["g++", *objs, "-o", "bin/FluidX3D", *FX_CFLAGS, *FX_LDLIBS], cwd=d,
                   check=True, capture_output=True, text=True)
    (d / "stamp").write_text(key)
    return exe


def fx_run(lattice: str, storage: str, sizes: list[int], plan: CPlan, copy_bw: float,
           timeout: float) -> tuple[list[dict], dict]:
    exe = fx_build(lattice, storage)
    shapes = [(n, n, 1) if lattice == "D2Q9" else (n, n, n) for n in sizes]
    env = {**os.environ, "CP_SIZES": ";".join(",".join(map(str, s)) for s in shapes),
           "CP_REPEATS": str(plan.repeats), "CP_MIN_TIME": str(plan.min_time)}
    t0 = time.perf_counter()
    p = subprocess.run([str(exe)], cwd=exe.parents[1], env=env, capture_output=True, text=True,
                       timeout=timeout)
    wall = time.perf_counter() - t0
    out = p.stdout + p.stderr
    res: dict[tuple[int, int, int], list[tuple[int, float]]] = {}
    for m in re.finditer(r"CP_RESULT nx=(\d+) ny=(\d+) nz=(\d+) cells=(\d+) steps=(\d+) "
                         r"seconds=([\d.eE+-]+)", out):
        nx, ny, nz, cells, steps = (int(m.group(k)) for k in range(1, 6))
        res.setdefault((nx, ny, nz), []).append((steps * cells, float(m.group(6))))
    dev = re.search(r"Device Name\s*\|\s*([^|\n]+?)\s*\|", out)
    info = {"returncode": p.returncode, "wall_s": wall,
            "device": dev.group(1) if dev else None,
            "lbm_type": sorted(set(re.findall(r"LBM Type\s*\|\s*([^|\n]+?)\s*\|", out)))}
    if not res:
        info["tail"] = out[-1500:]
    runs = []
    label = {"fp32": "FP32/FP32", "fp16s": "FP32/FP16S", "fp16c": "FP32/FP16C"}[storage]
    for (nx, ny, nz), meas in res.items():
        size = [nx, ny] if lattice == "D2Q9" else [nx, ny, nz]
        mlups = [lu / t / 1e6 for lu, t in meas]
        steps = meas[0][0] // (nx * ny * nz)
        runs.append(_record("FluidX3D", label, lattice, storage, "periodic box at rest", size,
                            mlups, steps, copy_bw,
                            notes="Esoteric-Pull in-place streaming; reads one flag byte per "
                                  "cell in addition to the minimal model; host sync per step"))
    return runs, info


# ----------------------------------------------------------------------------- Lettuce
def lt_run(jobs: list[dict], plan: CPlan, copy_bw: float, timeout: float
           ) -> tuple[list[dict], dict]:
    if not LT_PY.exists():
        return [], {"error": f"{LT_PY} not found"}
    cfg = {"runs": jobs, "min_time": plan.min_time, "repeats": plan.repeats}
    t0 = time.perf_counter()
    p = subprocess.run([str(LT_PY), "-I", str(ROOT / "bench" / "lettuce_worker.py"),
                        json.dumps(cfg)], capture_output=True, text=True, timeout=timeout,
                       cwd=str(ROOT / "bench"), env={**os.environ, **LT_BUILD_ENV})
    info: dict = {"returncode": p.returncode, "wall_s": time.perf_counter() - t0, "errors": []}
    runs = []
    for line in p.stdout.splitlines():
        if not line.startswith("CP_JSON "):
            continue
        r = json.loads(line[8:])
        if "header" in r:
            info.update(r["header"])
            continue
        if "error" in r:
            info["errors"].append(r)
            log(f"  Lettuce {r['dim']}D n={r['n']} native={r['native']}: {r['error']}")
            continue
        lattice = "D2Q9" if r["dim"] == 2 else "D3Q19"
        mlups = [r["nodes"] * r["steps"] / t / 1e6 for t in r["times"]]
        runs.append(_record(
            "Lettuce", "native CUDA" if r["native"] else "PyTorch", lattice, "fp32",
            "periodic Taylor-Green", [r["n"]] * r["dim"], mlups, r["steps"], copy_bw,
            notes=("generated CUDA extension, one kernel per step + device sync"
                   if r["native"] else "torch.roll streaming, eager PyTorch") +
                  f"; peak {r['peak_MiB']:.0f} MiB; finite={r['finite']}",
            peak_MiB=r["peak_MiB"]))
    if p.returncode != 0:
        info["tail"] = (p.stdout + p.stderr)[-1500:]
    return runs, info


# ----------------------------------------------------------------------------- pylbm
def pylbm_runs(plan: CPlan, copy_bw: float) -> list[dict]:
    from pylbm.benchmark import PLANS as BPLANS
    from pylbm.benchmark import measure

    bplan = BPLANS["quick" if plan.name == "quick" else "full"]
    bplan.min_time, bplan.repeats = plan.min_time, plan.repeats
    runs = []
    for dim, sizes in ((2, plan.sizes_2d), (3, plan.sizes_3d)):
        for backend, variant in PYLBM_VARIANTS:
            for n in sizes:
                try:
                    r = measure(backend, variant, dim, n, bplan, copy_bw, log=lambda _m: None)
                except Exception as e:
                    log(f"  pylbm {backend}/{variant} {n}^{dim}: {type(e).__name__}: {e}")
                    continue
                if r is None:
                    continue
                mlups = [r["min"], r["median"], r["max"]]  # keep pylbm's own stats below
                rec = _record("pylbm", f"{backend} {variant}", r["lattice"],
                              "fp16" if "fp16" in variant else "fp32", "lid-driven cavity",
                              r["size"], mlups, r["steps_per_repeat"], copy_bw, notes=r["notes"])
                rec.update(repeats=r["repeats"], median=r["median"], min=r["min"],
                           max=r["max"])
                rec["effective_GBs"] = r["median"] * 1e6 * rec["bytes_per_unit"] / 1e9
                rec["pct_copy_bw"] = 100 * rec["effective_GBs"] / copy_bw
                rec["pct_spec_bw"] = 100 * rec["effective_GBs"] / SPEC_BW
                runs.append(rec)
                _log_run(rec)
    return runs


# ----------------------------------------------------------------------------- driver
def reference_ceiling() -> tuple[float, str]:
    p = ROOT / "results" / "rtx3070-laptop.json"
    if p.exists():
        return float(json.loads(p.read_text())["ceiling"]["copy_bandwidth_GBs"]), p.name
    return 361.0, "SPEC.md (361 GB/s)"


def run(plan_name: str, out: Path, skip: set[str]) -> dict:
    from pylbm.benchmark import _versions, gpu_state

    plan = PLANS[plan_name]
    copy_bw, ceil_src = reference_ceiling()
    t_start = time.perf_counter()
    log(f"[counterparts:{plan_name}] ceiling {copy_bw:.1f} GB/s from {ceil_src}")
    gpu0 = gpu_state()
    runs: list[dict] = []
    builds: dict[str, object] = {}
    timeout = 120.0 if plan_name == "quick" else 900.0
    if "fluidx3d" not in skip:
        t_build = time.perf_counter()
        for lattice in ("D2Q9", "D3Q19"):  # build outside the timed budget
            for st in FX_STORAGES:
                fx_build(lattice, st)
        builds["fluidx3d_build_s"] = time.perf_counter() - t_build
    if "pylbm" not in skip:
        log("-- pylbm")
        runs += pylbm_runs(plan, copy_bw)
    fx_info: dict[str, object] = {}
    if "fluidx3d" not in skip:
        log("-- FluidX3D")
        for lattice, sizes in (("D2Q9", plan.sizes_2d), ("D3Q19", plan.sizes_3d)):
            for st in FX_STORAGES:
                try:
                    rs, info = fx_run(lattice, st, sizes, plan, copy_bw, timeout)
                except Exception as e:
                    rs, info = [], {"error": f"{type(e).__name__}: {e}"}
                fx_info[f"{lattice}-{st}"] = info
                if not rs:
                    log(f"  FluidX3D {lattice} {st}: no result ({info})")
                for r in rs:
                    _log_run(r)
                runs += rs
    lt_info: dict = {}
    if "lettuce" not in skip:
        log("-- Lettuce")
        jobs = [{"dim": 2, "n": n, "native": nat} for nat in (False, True)
                for n in plan.sizes_2d]
        jobs += [{"dim": 3, "n": n, "native": nat} for nat in (False, True)
                 for n in plan.lettuce_3d]
        try:
            rs, lt_info = lt_run(jobs, plan, copy_bw, timeout)
        except Exception as e:
            rs, lt_info = [], {"error": f"{type(e).__name__}: {e}"}
        for r in rs:
            _log_run(r)
        runs += rs
    result = {
        "machine": _versions(),
        "ceiling": {"copy_bandwidth_GBs": copy_bw, "source": ceil_src,
                    "spec_bandwidth_GBs": SPEC_BW},
        "plan": plan_name, "provisional": plan_name != "full",
        "metric": ("MLUPS; bytes_per_unit = 2 q s (minimal model, s = bytes per stored "
                   "population); effective_GBs = MLUPS * bytes_per_unit; pct_copy_bw against "
                   "the ceiling above"),
        "counterparts": {
            "FluidX3D": {"url": "https://github.com/ProjectPhysX/FluidX3D",
                         "commit": _git_head(FX_SRC), "pinned": FX_COMMIT,
                         "host_flags": " ".join(["g++", *FX_CFLAGS, *FX_LDLIBS]),
                         "defines": "D2Q9|D3Q19, SRT, BENCHMARK, [FP16S|FP16C]",
                         "alteration": "benchmark main_setup replaced by a timing harness "
                                       "(see bench/counterparts.py)",
                         "runs": fx_info, **builds},
            "Lettuce": {"url": "https://github.com/lettucecfd/lettuce",
                        "commit": _git_head(LT_SRC), "pinned": LT_COMMIT,
                        "python": str(LT_PY), "native_build_env": LT_BUILD_ENV,
                        "case": "TaylorGreenVortex Re=1 Ma=0.05, BGK, PRE_STREAMING, float32",
                        **lt_info},
        },
        "license_note": LICENSE_NOTE,
        "gpu_state_start": gpu0, "gpu_state_end": gpu_state(),
        "wall_time_s": time.perf_counter() - t_start,
        "runs": runs,
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=1))
    log(f"[counterparts] wrote {out} ({len(runs)} runs, {result['wall_time_s']:.0f} s)")
    return result


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--quick", action="store_true")
    g.add_argument("--full", action="store_true")
    ap.add_argument("--out", default=str(ROOT / "results" / "counterparts.json"))
    ap.add_argument("--skip", nargs="*", default=[], choices=["pylbm", "fluidx3d", "lettuce"])
    ap.add_argument("--build-only", action="store_true", help="only build FluidX3D binaries")
    a = ap.parse_args()
    if a.build_only:
        for lattice in ("D2Q9", "D3Q19"):
            for st in FX_STORAGES:
                log(str(fx_build(lattice, st)))
        return
    run("full" if a.full else "quick", Path(a.out), set(a.skip))


if __name__ == "__main__":
    main()
